export const ADMIN_LANGS: AdminLang[] = ["ru", "en", "hy"];

export function normalizeAdminLang(value?: string | null): AdminLang {
  if (value === "en" || value === "hy" || value === "ru") {
    return value;
  }
  return "ru";
}

